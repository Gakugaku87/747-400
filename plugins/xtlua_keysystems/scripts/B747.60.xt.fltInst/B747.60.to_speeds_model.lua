-- the indices around x in the list t (increasing or decreasing) and the
-- fraction between them, held at the ends
local function bracket(t, x)
    local n = #t
    local inc = t[n] > t[1]
    if (inc and x <= t[1]) or (not inc and x >= t[1]) then return 1, 1, 0 end
    if (inc and x >= t[n]) or (not inc and x <= t[n]) then return n, n, 0 end
    for i = 1, n - 1 do
        local a, b = t[i], t[i + 1]
        if (inc and x <= b) or (not inc and x >= b) then return i, i + 1, (x - a) / (b - a) end
    end
    return n, n, 0
end
local function round(x) return math.floor(x + 0.5) end
-- a minimum in whole knots: up (not under the table's)
local function up(x) return math.ceil(x - 1e-6) end

-- the region (1 A to 5 E) for a temperature (C) and pressure altitude (ft):
-- the lowest whose top is above it (on a line the higher one); beyond the
-- chart (above region E's top, hotter than its right edge) region E, below
-- -2,000 ft or colder than -60 C the chart's edge (estimates; before, no
-- region there: no speeds)
local function line_top(line, t)
    if t <= line[1][1] then return line[1][2] end
    for i = 2, #line do
        local a, b = line[i - 1], line[i]
        if t <= b[1] then return a[2] + (b[2] - a[2]) * (t - a[1]) / (b[1] - a[1]) end
    end
    return -math.huge
end
function M.region(t_c, pa_ft)
    local h = math.max(-2000, pa_ft)
    for i = 1, #M.LINES - 1 do
        if h < line_top(M.LINES[i], t_c) then return i end
    end
    return #M.LINES
end

-- a weight row's value (kg; held at 200 and 420 t)
local function by_weight(row, w)
    w = math.max(M.W0, math.min(M.W1, w))
    local i = math.min(#row - 1, math.floor((w - M.W0) / M.DW) + 1)
    local w1 = M.W0 + (i - 1) * M.DW
    return row[i] + (row[i + 1] - row[i]) * (w - w1) / M.DW
end
-- the V1 wind adjustment (kt) for a weight (kg) and headwind (kt)
function M.wind_adjustment(weight_kg, hw)
    local i1, i2, f = bracket(M.WINDS, hw)
    local a, b = by_weight(M.V1_WIND[i1], weight_kg), by_weight(M.V1_WIND[i2], weight_kg)
    return a + (b - a) * f
end
-- the tables' speeds (whole knots) for flaps, a region, a weight (kg) and a
-- headwind (kt)
function M.table_speeds(flaps, region, weight_kg, hw)
    local v1 = round(by_weight(M.V1[flaps][region], weight_kg) + M.wind_adjustment(weight_kg, hw or 0))
    local vr = round(by_weight(M.VR[flaps][region], weight_kg))
    local v2 = round(by_weight(M.V2[flaps][region], weight_kg))
    return v1, vr, v2
end

-- VMCG and VRMIN (KIAS) in one table for an OAT (C) and pressure altitude
-- (ft)
local function table_minimums(tab, oat_c, pa_ft)
    local t = tab.f and oat_c * 9 / 5 + 32 or oat_c
    local i1, i2, fi = bracket(tab.oat, t)
    local j1, j2, fj = bracket(M.PA, pa_ft)
    local r1, r2 = tab.rows[i1], tab.rows[i2]
    local function cell(k)
        local a = r1[2 * j1 - 1 + k] + (r1[2 * j2 - 1 + k] - r1[2 * j1 - 1 + k]) * fj
        local b = r2[2 * j1 - 1 + k] + (r2[2 * j2 - 1 + k] - r2[2 * j1 - 1 + k]) * fj
        return a + (b - a) * fi
    end
    return cell(0), cell(1)
end
-- VMCG and VRMIN (KIAS) for an engine type, the takeoff thrust reduction
-- (%: 0 TO, else the derate), the actual OAT (C) and the pressure altitude
-- (ft)
function M.minimums(engine, pct, oat_c, pa_ft)
    local set = M.ENGINES[engine] or PW
    pct = math.max(0, pct or 0)
    local last = set[#set]
    if pct >= last.pct then return table_minimums(last.vm, oat_c, pa_ft) end
    for k = 1, #set - 1 do
        local a, b = set[k], set[k + 1]
        if pct <= b.pct then
            local va, ra = table_minimums(a.vm, oat_c, pa_ft)
            if pct == a.pct then return va, ra end
            local vb, rb = table_minimums(b.vm, oat_c, pa_ft)
            local f = (pct - a.pct) / (b.pct - a.pct)
            return va + (vb - va) * f, ra + (rb - ra) * f
        end
    end
end
-- the V2 for VRMIN (KIAS) of the rating nearest the reduction, for flaps, a
-- weight (kg) and VR; nil without the flaps' table
function M.v2_for_vrmin(engine, pct, flaps, weight_kg, vr)
    local set = M.ENGINES[engine] or PW
    pct = math.max(0, pct or 0)
    local best = set[1]
    for _, e in ipairs(set) do
        if math.abs(e.pct - pct) <= math.abs(best.pct - pct) then best = e end
    end
    local t = best.v2[flaps]
    if not t then return nil end
    local w = t.lb and weight_kg / M.LB_KG / 1000 or weight_kg / 1000
    local i1, i2, fi = bracket(t.w, w)
    local j1, j2, fj = bracket(t.vr, vr)
    local function row(i) return t.v2[i][j1] + (t.v2[i][j2] - t.v2[i][j1]) * fj end
    return row(i1) + (row(i2) - row(i1)) * fi
end

-- the takeoff speeds (whole knots). inp: flaps (10, 20), weight_kg, hw
-- (the TAKEOFF REF headwind, kt), oat_c (actual), sel_c (the assumed
-- temperature or nil), pa_ft (pressure altitude), engine (type), pct (the
-- takeoff thrust reduction, %). Returns v1, vr, v2 and a table of the
-- working (region, vmcg, vrmin: the reused out table)
local info = {}
function M.speeds(inp)
    local t = inp.oat_c
    if inp.sel_c and inp.sel_c > t then t = inp.sel_c end
    local region = M.region(t, inp.pa_ft)
    local v1, vr, v2 = M.table_speeds(inp.flaps, region, inp.weight_kg, inp.hw)
    local vmcg, vrmin = M.minimums(inp.engine, inp.pct, inp.oat_c, inp.pa_ft)
    vmcg, vrmin = up(vmcg), up(math.max(vrmin, vmcg))
    if vr < vrmin then
        vr = vrmin
        local v2r = M.v2_for_vrmin(inp.engine, inp.pct, inp.flaps, inp.weight_kg, vr)
        if v2r and up(v2r) > v2 then v2 = up(v2r) end
    end
    if v1 < vmcg then v1 = vmcg end
    if v1 > vr then v1 = vr end
    info.region, info.vmcg, info.vrmin = region, vmcg, vrmin
    return v1, vr, v2, info
end

return M
