-- the indices around x in the list t (increasing or decreasing) and the
-- fraction between them, held at the ends
local function bracket(t, x)
    local n = #t
    local inc = t[n] > t[1]
    if (inc and x <= t[1]) or (not inc and x >= t[1]) then return 1, 1, 0 end
    if (inc and x >= t[n]) or (not inc and x <= t[n]) then return n, n, 0 end
    for i = 1, n - 1 do
        local a, b = t[i], t[i + 1]
        if (inc and x <= b) or (not inc and x >= b) then return i, i + 1, (x - a) / (b - a) end
    end
    return n, n, 0
end
local function round(x) return math.floor(x + 0.5) end
-- a minimum in whole knots: up (not under the table's)
local function up(x) return math.ceil(x - 1e-6) end

-- the region (1 A to 13 M) for a temperature (C) and pressure altitude
-- (ft): the first whose boundary is above it (on a line the higher one).
-- 10 C and below the chart's left edge (FPPM); a line from the top edge
-- not reached left of its start; above 10,000 ft and below -2,000 ft the
-- chart's edges, hotter than its right edge M (estimates)
local function line_top(line, t)
    if t <= line[1][1] then
        if line[1][2] >= 10000 and t < line[1][1] then return math.huge end
        return line[1][2]
    end
    for i = 2, #line do
        local a, b = line[i - 1], line[i]
        if t <= b[1] then return a[2] + (b[2] - a[2]) * (t - a[1]) / (b[1] - a[1]) end
    end
    return -math.huge
end
function M.region(t_c, pa_ft)
    local h = math.max(-2000, math.min(10000, pa_ft))
    for i = 1, #M.LINES do
        if h < line_top(M.LINES[i], t_c) then return i end
    end
    return #M.LINES + 1
end

-- a weight row's value (kg; held at 200 and 400 t: estimate)
local function by_weight(row, w)
    w = math.max(M.W0, math.min(M.W1, w))
    local i = math.min(#row - 1, math.floor((w - M.W0) / M.DW) + 1)
    local w1 = M.W0 + (i - 1) * M.DW
    return row[i] + (row[i + 1] - row[i]) * (w - w1) / M.DW
end
-- a table's value between its rows and columns, held at the ends
local function table2(rows_x, cols_x, t, x, y)
    local i1, i2, fi = bracket(rows_x, x)
    local j1, j2, fj = bracket(cols_x, y)
    local function row(i) return t[i][j1] + (t[i][j2] - t[i][j1]) * fj end
    return row(i1) + (row(i2) - row(i1)) * fi
end
-- the V1 wind adjustment (kt) for a weight (kg) and headwind (kt, a
-- tailwind negative), and the V1 slope adjustment for a runway slope (%,
-- uphill +; the FMC takes 0.0 to 2.0 % up or down: FMSPG p.106)
function M.wind_adjustment(weight_kg, hw)
    return table2(M.SW_W, M.WINDS, M.V1_WIND, weight_kg, hw or 0)
end
function M.slope_adjustment(weight_kg, slope)
    return table2(M.SW_W, M.SLOPES, M.V1_SLOPE, weight_kg, slope or 0)
end

-- inside a polygon ({x, y} points)
local function inside(poly, x, y)
    local c, j = false, #poly
    for i = 1, #poly do
        local xi, yi, xj, yj = poly[i][1], poly[i][2], poly[j][1], poly[j][2]
        if (yi > y) ~= (yj > y) and x < xi + (xj - xi) * (y - yi) / (yj - yi) then c = not c end
        j = i
    end
    return c
end
-- the V1, VR and V2 altitude adjustments (kt) for flaps, a weight (kg) and
-- the pressure altitude (ft): the charts' areas; a weight outside 200 to
-- 400 t or an altitude outside -2,000 to 10,000 ft at the chart's edge
-- (estimates)
function M.altitude_adjustments(flaps, weight_kg, pa_ft)
    local set = M.ALT_ADJ[flaps]
    if not set then return 0, 0, 0 end
    local w = math.max(200.001, math.min(399.999, weight_kg / 1000))
    local h = math.max(-1999.9, math.min(9999.9, pa_ft))
    local function adj(z)
        if z.z2 and inside(z.z2, w, h) then return 2 end
        if inside(z.z1, w, h) then return 1 end
        return 0
    end
    return adj(set.V1), adj(set.VR), adj(set.V2)
end

-- a table's speed (KIAS, unrounded) for the thrust reduction (%), flaps,
-- "V1", "VR" or "V2", a region and a weight (kg): between the tables of the
-- reductions around it, over the last the last's (estimates)
local function rated(pct, flaps, kind, region, w)
    local r = M.RATINGS
    pct = math.max(0, pct or 0)
    if pct >= r[#r] then return by_weight(M.TABLES[r[#r]][flaps][kind][region], w) end
    for k = 1, #r - 1 do
        local a, b = r[k], r[k + 1]
        if pct <= b then
            local va = by_weight(M.TABLES[a][flaps][kind][region], w)
            if pct == a then return va end
            local vb = by_weight(M.TABLES[b][flaps][kind][region], w)
            return va + (vb - va) * (pct - a) / (b - a)
        end
    end
end
-- the tables' speeds (whole knots) for flaps, a region, a weight (kg), the
-- headwind (kt), the runway slope (%, uphill +), the pressure altitude (ft)
-- and the thrust reduction (%): V1 with the slope and wind adjustments, all
-- three with the altitude adjustments, V1 not over VR (FPPM p.21 (1.1.3))
function M.table_speeds(flaps, region, weight_kg, hw, slope, pa_ft, pct)
    local a1, ar, a2 = M.altitude_adjustments(flaps, weight_kg, pa_ft or 0)
    local v1 = round(rated(pct, flaps, "V1", region, weight_kg) + M.slope_adjustment(weight_kg, slope)
        + M.wind_adjustment(weight_kg, hw) + a1)
    local vr = round(rated(pct, flaps, "VR", region, weight_kg) + ar)
    local v2 = round(rated(pct, flaps, "V2", region, weight_kg) + a2)
    if v1 > vr then v1 = vr end
    return v1, vr, v2
end

-- VMCG and VRMIN (KIAS) in one table for an OAT (C) and pressure altitude
-- (ft)
local function table_minimums(tab, oat_c, pa_ft)
    local t = tab.f and oat_c * 9 / 5 + 32 or oat_c
    local i1, i2, fi = bracket(tab.oat, t)
    local j1, j2, fj = bracket(M.PA, pa_ft)
    local r1, r2 = tab.rows[i1], tab.rows[i2]
    local function cell(k)
        local a = r1[2 * j1 - 1 + k] + (r1[2 * j2 - 1 + k] - r1[2 * j1 - 1 + k]) * fj
        local b = r2[2 * j1 - 1 + k] + (r2[2 * j2 - 1 + k] - r2[2 * j1 - 1 + k]) * fj
        return a + (b - a) * fi
    end
    return cell(0), cell(1)
end
-- VMCG and VRMIN (KIAS) for an engine type, the takeoff thrust reduction
-- (%: 0 TO, else the derate), the actual OAT (C) and the pressure altitude
-- (ft)
function M.minimums(engine, pct, oat_c, pa_ft)
    local set = M.ENGINES[engine] or M.ENGINES[0]
    pct = math.max(0, pct or 0)
    local last = set[#set]
    if pct >= last.pct then return table_minimums(last.vm, oat_c, pa_ft) end
    for k = 1, #set - 1 do
        local a, b = set[k], set[k + 1]
        if pct <= b.pct then
            local va, ra = table_minimums(a.vm, oat_c, pa_ft)
            if pct == a.pct then return va, ra end
            local vb, rb = table_minimums(b.vm, oat_c, pa_ft)
            local f = (pct - a.pct) / (b.pct - a.pct)
            return va + (vb - va) * f, ra + (rb - ra) * f
        end
    end
end
-- the V2 for VRMIN (KIAS) of the rating nearest the reduction, for flaps, a
-- weight (kg) and VR; nil without the flaps' table
function M.v2_for_vrmin(engine, pct, flaps, weight_kg, vr)
    local set = M.ENGINES[engine] or M.ENGINES[0]
    pct = math.max(0, pct or 0)
    local best = set[1]
    for _, e in ipairs(set) do
        if math.abs(e.pct - pct) <= math.abs(best.pct - pct) then best = e end
    end
    local t = best.v2[flaps]
    if not t then return nil end
    local w = t.lb and weight_kg / M.LB_KG / 1000 or weight_kg / 1000
    local i1, i2, fi = bracket(t.w, w)
    local j1, j2, fj = bracket(t.vr, vr)
    local function row(i) return t.v2[i][j1] + (t.v2[i][j2] - t.v2[i][j1]) * fj end
    return row(i1) + (row(i2) - row(i1)) * fi
end

-- the takeoff speeds (whole knots). inp: flaps (10, 20), weight_kg, hw
-- (the TAKEOFF REF headwind, kt), slope (its runway slope, %, uphill +; nil
-- none), oat_c (actual), sel_c (the assumed temperature or nil), pa_ft
-- (pressure altitude), engine (type), pct (the takeoff thrust reduction,
-- %). Returns v1, vr, v2 and a table of the working (region, vmcg, vrmin:
-- the reused out table)
local info = {}
function M.speeds(inp)
    local assumed = inp.sel_c ~= nil and inp.sel_c > inp.oat_c
    local region = M.region(assumed and inp.sel_c or inp.oat_c, inp.pa_ft)
    local v1, vr, v2 = M.table_speeds(inp.flaps, region, inp.weight_kg, inp.hw, inp.slope, inp.pa_ft, inp.pct)
    local vmcg, vrmin = M.minimums(inp.engine, inp.pct, inp.oat_c, inp.pa_ft)
    vmcg, vrmin = up(vmcg), up(math.max(vrmin, vmcg))
    if vr < vrmin then
        if assumed then
            -- FPPM p.21 (1.1.3) C, D: V2 up by as much as VR
            v2 = v2 + (vrmin - vr)
        else
            local v2r = M.v2_for_vrmin(inp.engine, inp.pct, inp.flaps, inp.weight_kg, vrmin)
            if v2r and up(v2r) > v2 then v2 = up(v2r) end
        end
        vr = vrmin
    end
    if v1 < vmcg then v1 = vmcg end
    if v1 > vr then v1 = vr end
    info.region, info.vmcg, info.vrmin = region, vmcg, vrmin
    return v1, vr, v2, info
end

