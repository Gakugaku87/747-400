local floor, max = math.floor, math.max

-- v at u on a curve {u1, v1, u2, v2, ...} (u rising); outside its ends the
-- end segment carried on (estimate)
local function curve(p, u)
    local n, i = #p, 3
    while i < n - 1 and u > p[i] do i = i + 2 end
    local u1, v1, u2, v2 = p[i - 2], p[i - 1], p[i], p[i + 1]
    return v1 + (v2 - v1) * (u - u1) / (u2 - u1)
end

-- along a family of guide lines (each {ref = its value at the reference
-- level, curve...}, ref rising) from the reference value r to u: between
-- the two lines around r by r's fraction between them at the reference
local function along(fam, r, u)
    local n = #fam
    if r < fam[1].ref or r > fam[n].ref then return nil end
    local i = 1
    while i < n - 1 and r > fam[i + 1].ref do i = i + 1 end
    local a, b = fam[i], fam[i + 1]
    local f = (r - a.ref) / (b.ref - a.ref)
    local va = curve(a, u)
    return va + f * (curve(b, u) - va)
end

local function chart(flaps)
    local d = DATA[tonumber(flaps)]
    if not d then return nil, "no field limit chart for flaps " .. tostring(flaps) end
    return d
end

-- the pressure-altitude lines around pa and pa's fraction between them
local function pa_index(d, pa)
    local P = d.pa_ft
    if not pa or pa < P[1] or pa > P[#P] then return nil end
    local j = 1
    while j < #P - 1 and pa > P[j + 1] do j = j + 1 end
    return j, (pa - P[j]) / (P[j + 1] - P[j])
end

local PA_OUT = "pressure altitude outside the chart's -2,000 to 10,000 ft"

local function limit_c(flaps, pa_ft, key)
    local d, why = chart(flaps)
    if not d then return nil, why end
    local j, f = pa_index(d, tonumber(pa_ft))
    if not j then return nil, PA_OUT end
    local c = d[key]
    return c[j] + f * (c[j + 1] - c[j])
end

function M.env_limit_c(flaps, pa_ft) return limit_c(flaps, pa_ft, "env_c") end
function M.atm_limit_c(flaps, pa_ft) return limit_c(flaps, pa_ft, "atm_c") end

-- the left part: 1000 kg at the REF LINE
local function ref_t(d, oat, pa, assumed)
    if not oat or not pa then return nil, "no OAT or pressure altitude" end
    local j, f = pa_index(d, pa)
    if not j then return nil, PA_OUT end
    if assumed then
        if oat > d.atm_c[j] + f * (d.atm_c[j + 1] - d.atm_c[j]) then
            return nil, "above the assumed temperature limit"
        end
    elseif oat > d.env_c[j] + f * (d.env_c[j + 1] - d.env_c[j]) then
        return nil, "above the environmental limit"
    end
    local t = max(oat, d.scale.oat_lo)
    local w1 = curve(d.pa[j], t)
    return w1 + f * (curve(d.pa[j + 1], t) - w1)
end

function M.ref_weight(flaps, oat_c, pa_ft, assumed)
    local d, why = chart(flaps)
    if not d then return nil, why end
    local w, why2 = ref_t(d, tonumber(oat_c), tonumber(pa_ft), assumed)
    if not w then return nil, why2 end
    return floor(w * 100 + 0.5) * 10
end

-- along a small chart's lines from a length on the chart's scale: its
-- outermost lines meet the REF LINE within a few feet of the scale's ends
-- (the drawing), so the length is kept between them
local function along_scale(fam, l, u)
    return along(fam, math.min(math.max(l, fam[1].ref), fam[#fam].ref), u)
end

