    if slope > s.slope or slope < -s.slope then return nil, "runway slope beyond the chart's +/-2 %" end
    if wind < -s.tail then return nil, "tailwind beyond the chart's 15 kt" end
    if wind > s.head then wind, note = s.head, "headwind taken as the chart's 40 kt" end
    if fla < s.ft_lo then return nil, "field length below the chart's 4,000 ft" end
    if fla > s.ft_hi then fla, note = s.ft_hi, "field length taken as the chart's 18,000 ft" end
    local l = along_scale(d.slope, fla, slope)
    if l < s.ft_lo then return nil, "below the chart's 4,000 ft after the slope correction" end
    if l > s.ft_hi then l, note = s.ft_hi, "corrected length taken as the chart's 18,000 ft" end
    l = along_scale(d.wind, l, wind)
    if l < s.ft_lo then return nil, "below the chart's 4,000 ft after the wind correction" end
    if l > s.ft_hi then l, note = s.ft_hi, "corrected length taken as the chart's 18,000 ft" end
    return l, note
end

function M.corrected_length(flaps, fla_ft, slope_pct, wind_kt)
    local d, why = chart(flaps)
    if not d then return nil, why end
    local l, note = corrected(d, tonumber(fla_ft), tonumber(slope_pct) or 0, tonumber(wind_kt) or 0)
    if not l then return nil, note end
    return floor(l + 1e-6), note
end

function M.limit_weight(flaps, oat_c, pa_ft, fla_ft, slope_pct, wind_kt, assumed)
    local d, why = chart(flaps)
    if not d then return nil, why end
    local r, why2 = ref_t(d, tonumber(oat_c), tonumber(pa_ft), assumed)
    if not r then return nil, why2 end
    local l, note = corrected(d, tonumber(fla_ft), tonumber(slope_pct) or 0, tonumber(wind_kt) or 0)
    if not l then return nil, note end
    if l < d.min_ft then return nil, "corrected field length below the minimum field length required" end
    local w = along(d.guide, r, l)
    if not w then return nil, "outside the chart's guide lines" end
    local s = d.scale
    if w < s.w_lo then return nil, "below the chart's 200,000 kg" end
    if w > s.w_hi then return s.w_hi * 1000, "above the chart: 460,000 kg or more" end
    return floor(w * 100 + 1e-6) * 10, note      -- down to 10 kg
end

-- the notes below the charts: packs off (0) or 1 pack on; 3 packs (the
-- charts' basis) 0. 2 packs are not in the notes: 0 (the 3-pack basis,
-- conservative: estimate)
function M.bleed_adjust_kg(flaps, packs)
    local d, why = chart(flaps)
    if not d then return nil, why end
    packs = tonumber(packs) or 3
    if packs <= 0 then return d.bleed[1] end
    if packs == 1 then return d.bleed[2] end
    return 0
end

return M
