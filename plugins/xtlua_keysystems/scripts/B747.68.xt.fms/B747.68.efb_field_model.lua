--    10 kt: the caller's to check). Headwind above the chart's 40 kt is taken
--    as 40 kt (conservative; note).
--  - Field length: below 4,000 ft (the scale) nil; above 18,000 ft, and a
--    length corrected past 18,000 ft, taken as 18,000 ft (conservative; note).
--  - The MINIMUM FIELD LENGTH REQUIRED line stands on the right part's
--    field length scale, which is the slope- and wind-corrected length: the
--    guide lines end on it. It is the minimum for V1 = VMCG (FPPM p.21
--    (1.1.3): no weight adjustment while the field length exceeds the
--    minimum shown on the Takeoff Field Limit chart). A corrected length
--    below it: nil.
--  - Weight: below the chart's 200,000 kg nil (no guide line to read; a
