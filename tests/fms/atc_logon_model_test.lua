-- Run from the repository root with LuaJIT: luajit tests/fms/atc_logon_model_test.lua
-- The ATC logon (6-1/6-2 step 12e; notes/ATA-34-61-FMC.md §113; FCOM
-- p.755-757, p.1431, p.1433; FMSPG p.258, p.277-280): LOGON TO, SEND and
-- its states, the connection and its end, the timers, ADS, the page's view.
local T = dofile("tests/lib/check.lua")("atc_logon_model")
local A = dofile("plugins/xtlua_keysystems/scripts/B747.68.xt.fms/B747.68.atc_logon_model.lua")
local OK = {flt_ok = true, ready = true, pos_ok = true, tail_ok = true}
local function view(s, inp) return A.view(s, inp or OK) end

local s = A.new()
T.equal(view(s).l1, "****", "LOGON TO: boxes")
T.equal(view(s).r1, "", "no SEND without a facility")
T.equal(view(s, {flt_ok = true, ready = true, pos_ok = false, tail_ok = true}).l1, "", "position invalid: blank (FMSPG p.277)")
T.equal(view(s, {flt_ok = true, ready = true, pos_ok = true, tail_ok = false}).l1, "", "tail number invalid: blank")
T.equal(A.enter_ctr(s, "KZ1K"), "INVALID ENTRY", "four letters only")
T.equal(A.enter_ctr(s, "KZA"), "INVALID ENTRY", "three letters: invalid")
T.equal(A.delete_ctr(s), "INVALID DELETE", "nothing to delete")
T.equal(A.enter_ctr(s, "KZAK"), nil, "KZAK")
T.equal(view(s).l1, "KZAK", "LOGON TO KZAK")
T.equal(view(s).r1, "SEND>", "SEND> with FLT NO and READY (FCOM p.755)")
T.equal(view(s, {flt_ok = false, ready = true, pos_ok = true, tail_ok = true}).r1, "", "no FLT NO: no SEND")
T.equal(view(s, {flt_ok = true, ready = false, pos_ok = true, tail_ok = true}).r1, "", "NO COMM: no SEND")
T.equal(A.delete_ctr(s), nil, "delete")
T.equal(view(s).l1, "****", "boxes again")
A.enter_ctr(s, "KZAK")

-- SEND, the network's acknowledgement, ATC's acceptance, the connection
T.check(not A.send(s, 0, false, true), "no SEND without FLT NO")
T.check(A.send(s, 0, true, true), "SEND")
T.equal(view(s).r1, "SENDING", "SENDING (FMSPG p.279)")
T.check(not A.send(s, 1, true, true), "no second SEND while sending")
A.ack(s)
T.equal(view(s).r1, "SENT", "SENT after the network's acknowledgement")
T.equal(#A.response(s, true), 0, "accepted: no message")
T.equal(view(s).r1, "ACCEPTED", "ACCEPTED")
T.equal(A.connect(s, "KZAK"), "ATC COMM ESTABLISHED", "the connection: ATC COMM ESTABLISHED (FCOM p.1431)")
T.equal(view(s).l1, "----", "LOGON TO: dashes (FMSPG p.278)")
T.equal(view(s).r1, "", "LOGON: blank")
T.equal(view(s).act, "KZAK", "ACT CTR KZAK")
A.set_next(s, "PANC")
T.equal(view(s).next, "PANC", "NEXT CTR PANC")
T.equal(A.delete_ctr(s), "INVALID DELETE", "dashes: no deletion")
local m = A.terminate(s, false)
T.equal(m[1], "ATC COMM TERMINATED", "SELECT OFF: ATC COMM TERMINATED")
T.equal(view(s).l1, "****", "boxes again")
T.equal(view(s).act, "", "no ACT CTR")
T.equal(view(s).next, "", "no NEXT CTR")

-- the timers: no acknowledgement, no response (RE-LOGON TO ATC COMM)
s = A.new()
A.enter_ctr(s, "KZAK")
A.send(s, 0, true, true)
T.equal(#A.update(s, 59, false), 0, "59 s without an acknowledgement: nothing")
A.update(s, 60, false)
T.equal(view(s).r1, "RESEND>", "60 s: RESEND> (estimate)")
T.check(A.send(s, 61, true, true), "RESEND")
A.ack(s)
T.equal(#A.update(s, 180, true), 0, "SENT 119 s: nothing")
m = A.update(s, 181, true)
T.equal(m[1], "RE-LOGON TO ATC COMM", "no response in 120 s: RE-LOGON TO ATC COMM (FMSPG p.258; the time an estimate)")
T.equal(view(s).r1, "RESEND>", "RESEND>")
-- a negative response
A.send(s, 200, true, true)
m = A.response(s, false)
T.equal(m[1], "RE-LOGON TO ATC COMM", "rejected: RE-LOGON TO ATC COMM")
T.equal(view(s).r1, "REJECTED", "REJECTED (FMSPG p.279)")
-- NO COMM for 16 minutes while connected: disconnected
s = A.new()
A.enter_ctr(s, "KZAK")
A.send(s, 0, true, true)
A.ack(s)
A.response(s, true)
A.connect(s, "KZAK")
T.equal(#A.update(s, 10, false), 0, "NO COMM begins")
T.equal(#A.update(s, 10 + 959, false), 0, "15:59 of NO COMM: connected still")
m = A.update(s, 10 + 960, false)
T.equal(m[1], "RE-LOGON TO ATC COMM", "16 minutes of NO COMM: RE-LOGON TO ATC COMM (FMSPG p.258)")
T.check(not s.comm, "disconnected")
-- READY again resets the count
s = A.new()
A.enter_ctr(s, "KZAK"); A.send(s, 0, true, true); A.ack(s); A.response(s, true); A.connect(s, "KZAK")
A.update(s, 10, false)
A.update(s, 500, true)
A.update(s, 600, false)
T.equal(#A.update(s, 600 + 959, false), 0, "READY between: the count again")
-- a new flight number
s = A.new()
A.enter_ctr(s, "KZAK"); A.send(s, 0, true, true)
m = A.new_flight(s)
T.equal(m[1], "RE-LOGON TO ATC COMM", "a flight number change during a logon: RE-LOGON TO ATC COMM")
A.send(s, 1, true, true); A.ack(s); A.response(s, true); A.connect(s, "KZAK")
m = A.new_flight(s)
T.equal(m[1], "ATC COMM TERMINATED", "while connected: ATC COMM ends")
-- a new facility while connected: shown, SEND
s = A.new()
A.enter_ctr(s, "KZAK"); A.send(s, 0, true, true); A.ack(s); A.response(s, true); A.connect(s, "KZAK")
A.enter_ctr(s, "PANC")
T.equal(view(s).l1, "PANC", "a new facility shows instead of the dashes")
T.equal(view(s).r1, "SEND>", "with SEND>")

-- ADS
s = A.new()
T.equal(s.ads, "ARM", "ADS (ARM)")
T.check(A.emerg_toggle(s) and s.emerg, "ADS EMERG SELECT ON")
A.ads_toggle(s)
T.check(s.ads == "OFF" and not s.emerg, "SELECT OFF: ADS (OFF), the emergency mode off")
T.check(not A.emerg_toggle(s), "ADS EMERG not with ADS off")
A.ads_toggle(s)
T.equal(s.ads, "ARM", "SELECT ARM: ADS (ARM)")
T.done()
