-- Run from the repository root with LuaJIT: luajit tests/fms/atc_request_model_test.lua
-- The ATC requests (6-1/6-2 step 12g2a; notes/ATA-34-61-FMC.md §116; FCOM
-- p.736-747; FMSPG p.298-327): the entries' forms and ranges, the altitude's
-- element by the altitude then, STEP AT and CRZ CLB, the offset's AT or
-- WEATHER, DELETE with what depends on it, five elements at most, VERIFY
-- REQUEST's rows and free text lines, the text sent.
local T = dofile("tests/lib/check.lua")("atc_request_model")
local Q = dofile("plugins/xtlua_keysystems/scripts/B747.68.xt.fms/B747.68.atc_request_model.lua")

-- the entries (FCOM p.736-743; FMSPG p.301-318)
T.equal(Q.alt_text("350"), "FL350", "XXX: a flight level")
T.equal(Q.alt_text("FL030"), "FL030", "FL030 the lowest (FMSPG p.301)")
T.check(not Q.alt_text("FL029"), "under FL030: invalid")
T.equal(Q.alt_text("FL451"), "FL451", "the maximum certified altitude (FCOM p.1311)")
T.check(not Q.alt_text("452"), "above it: invalid")
T.equal(Q.alt_text("12000"), "12000", "feet")
T.equal(Q.alt_text("9000"), "9000", "four digits: feet")
T.check(not Q.alt_text("25100"), "feet over 25,000: invalid")
T.equal(Q.alt_text("3000M"), "3000M", "metres")
T.check(not Q.alt_text("16100M"), "metres over 16,000: invalid")
T.equal(Q.alt_text("FL350/FL370"), "FL350/FL370", "a block of flight levels")
T.equal(Q.alt_text("12000/FL200"), "12000/FL200", "a block of feet and a flight level")
T.check(not Q.alt_text("FL370/FL350"), "a block: the lower first (estimate)")
T.check(not Q.alt_text("3000M/4000M"), "no block in metres")
T.equal(Q.time_text("1234"), "1234Z", "a time hhmm")
T.check(not Q.time_text("2400") and not Q.time_text("1260"), "hh 00-23, mm 00-59")
T.equal(Q.speed_text("285"), "290", "IAS to the nearest 10 kt (FMSPG p.310)")
T.equal(Q.speed_text("380"), "380", "380 the highest")
T.check(not Q.speed_text("381") and not Q.speed_text("099"), "IAS 100-380")
T.equal(Q.speed_text(".8"), ".80", "Mach one digit")
T.equal(Q.speed_text(".855"), ".86", "Mach three digits: to the nearest .01")
T.check(Q.speed_text(".61") and not Q.speed_text(".60") and not Q.speed_text(".915"), "Mach .61-.91")
T.equal(Q.offset_text("L10"), "L10", "offset L")
T.equal(Q.offset_text("R5"), "R5", "offset R")
T.equal(Q.offset_text("10"), "10", "just the distance (FCOM p.737)")
T.check(not Q.offset_text("L0") and not Q.offset_text("R100") and not Q.offset_text("X10"), "1-99, L or R")
T.equal(Q.degrees_text("5"), "005", "a heading")
T.equal(Q.degrees_text("360"), "360", "000-360")
T.check(not Q.degrees_text("361"), "over 360: invalid")

-- the altitude's element by the altitude then (FMSPG p.304-305)
local r = Q.new("REQUEST")
T.equal(Q.enter(r, "alt", "FL350", 30000), nil, "FL350 at FL300")
T.equal(Q.elements(r)[1].text, "REQUEST CLIMB TO FL350", "more than 150 ft above: CLIMB TO")
Q.enter(r, "alt", "FL301", 30000)
T.equal(Q.elements(r)[1].text, "REQUEST FL301", "within 150 ft: level")
Q.enter(r, "alt", "FL290", 30000)
T.equal(Q.elements(r)[1].text, "REQUEST DESCENT TO FL290", "below: DESCENT TO")
Q.enter(r, "alt", "FL350/FL370", 30000)
T.equal(Q.elements(r)[1].text, "REQUEST BLOCK FL350 TO FL370", "a block")
T.equal(Q.enter(r, "alt", "FL470", 30000), Q.INVALID, "an invalid altitude")
T.equal(r.alt, "FL350/FL370", "kept")

-- STEP AT and CRZ CLB (FMSPG p.307-308)
r = Q.new("REQUEST")
Q.enter(r, "alt", "FL370", 35000)
T.equal(Q.enter(r, "step_at", "1234", 35000), nil, "STEP AT a time")
T.equal(Q.elements(r)[1].text, "AT 1234Z REQUEST CLIMB TO FL370", "AT [time] REQUEST CLIMB TO")
T.equal(Q.select(r, "crz_clb"), nil, "CRZ CLB with STEP AT: nothing")
T.check(not r.crz_clb, "not selected")
Q.delete(r, "step_at")
Q.select(r, "crz_clb")
T.equal(Q.elements(r)[1].text, "REQUEST CRUISE CLIMB TO FL370", "CRZ CLB")
T.equal(Q.enter(r, "step_at", "1234", 35000), Q.INVALID, "STEP AT after CRZ CLB: invalid")
T.equal(Q.set_place(r, "step_at", "GGW"), Q.INVALID, "a position too")
Q.delete(r, "crz_clb")
T.equal(Q.elements(r)[1].text, "REQUEST CLIMB TO FL370", "CRZ CLB deleted: CLIMB TO again")
T.equal(Q.set_place(r, "step_at", "GGW"), nil, "STEP AT a position")
T.equal(Q.elements(r)[1].text, "AT GGW REQUEST CLIMB TO FL370", "AT [position] REQUEST CLIMB TO")
Q.enter(r, "alt", "FL350", 35000)
T.equal(r.step_at, nil, "a level altitude: no STEP AT")
T.equal(Q.select(r, "crz_clb"), nil, "CRZ CLB on a level request: nothing")
T.check(not r.crz_clb, "not selected")

-- the reasons, DELETE (FMSPG p.302, p.307)
r = Q.new("REQUEST")
T.equal(Q.select(r, "alt_wx"), nil, "DUE TO WEATHER without an altitude: nothing")
T.check(not r.alt_wx, "not selected")
Q.enter(r, "alt", "FL350", 30000)
Q.select(r, "pilot_disc")
Q.select(r, "own_sep")
Q.select(r, "alt_perf")
Q.select(r, "alt_wx")
local texts = {}
for _, e in ipairs(Q.elements(r)) do texts[#texts + 1] = e.text end
T.equal(table.concat(texts, "|"), "REQUEST CLIMB TO FL350|AT PILOTS DISCRETION|MAINTAIN OWN SEPARATION AND VMC|"
    .. "DUE TO AIRCRAFT PERFORMANCE|DUE TO WEATHER", "the altitude's elements")
-- five elements at most (FMSPG p.298)
T.equal(Q.enter(r, "spd", ".86", 30000), Q.LIMIT, "a sixth: MSG LIMIT EXCEEDED")
T.equal(r.spd, nil, "not taken")
T.equal(Q.delete(r, "alt"), nil, "DELETE the altitude")
T.check(not r.alt and not r.pilot_disc and not r.own_sep and not r.alt_perf and not r.alt_wx and not r.alt_dir,
    "its reasons deleted with it (FMSPG p.307)")
T.equal(Q.delete(r, "alt"), "INVALID DELETE", "nothing to delete")
T.check(not Q.any(r), "nothing: no ERASE REQUEST")

-- the offset: AT or WEATHER (FMSPG p.312-314)
r = Q.new("REQUEST")
Q.enter(r, "off", "R15", 0)
T.equal(Q.elements(r)[1].text, "REQUEST OFFSET R15NM", "REQUEST OFFSET")
Q.select(r, "off_wx")
T.equal(Q.elements(r)[1].text, "REQUEST WEATHER DEVIATION UP TO R15NM", "DUE TO WEATHER: WEATHER DEVIATION UP TO")
T.check(not Q.can(r, "off_at"), "with WEATHER: no OFFSET AT")
Q.delete(r, "off_wx")
Q.set_place(r, "off_at", "GGW")
T.equal(Q.elements(r)[1].text, "AT GGW REQUEST OFFSET R15NM", "AT [position] REQUEST OFFSET")
T.check(not Q.can(r, "off_wx"), "with OFFSET AT: no WEATHER")
Q.delete(r, "off")
T.check(not r.off_at, "the offset deleted: OFFSET AT too")

-- VERIFY REQUEST: FCOM p.744's request on two pages
r = Q.new("REQUEST")
Q.enter(r, "off", "L10", 30000)
Q.set_place(r, "off_at", "GGW")
Q.enter(r, "alt", "FL350", 30000)
Q.select(r, "alt_wx")
Q.enter(r, "spd", ".86", 30000)
local rows = Q.verify_rows(r, true)
local heads = {}
for k = 1, 5 do heads[k] = rows[k].head .. "=" .. rows[k].data .. (rows[k].unit or "") end
T.equal(table.concat(heads, "|"), "AT=GGW|REQUEST OFFSET=L10NM|/REQUEST CLIMB TO=FL350|/DUE TO=WEATHER|/REQUEST=.86",
    "the rows (FCOM p.744)")
T.equal(Q.free_count(r), 4, "the elements fill page 1: four free text lines on page 2")
T.equal(rows[6].head .. rows[6].data, "/FREE TEXT<", "the free text's header and prompt")
T.equal(Q.pages(rows), 2, "1/2 and 2/2 (FCOM p.744)")
T.equal(Q.text(r), "AT GGW REQUEST OFFSET L10NM REQUEST CLIMB TO FL350 DUE TO WEATHER REQUEST .86", "the text sent")
Q.set_free(r, 1, "TURBULENCE")
T.equal(Q.text(r), "AT GGW REQUEST OFFSET L10NM REQUEST CLIMB TO FL350 DUE TO WEATHER REQUEST .86 TURBULENCE",
    "with the free text")
T.equal(Q.verify_rows(r, true)[6].data, "TURBULENCE", "an entered line: its text")
-- FMSPG p.324: REQUEST FL370 DUE TO WEATHER, two free text lines
r = Q.new("REQUEST")
Q.enter(r, "alt", "FL370", 37000)
Q.select(r, "alt_wx")
rows = Q.verify_rows(r, true)
T.equal(#rows, 4, "two rows and two free text lines (to line 4)")
T.equal(rows[1].head .. "=" .. rows[1].data, "REQUEST=FL370", "REQUEST FL370")
T.equal(rows[2].head .. "=" .. rows[2].data, "/DUE TO=WEATHER", "/DUE TO WEATHER")
T.equal(rows[3].head, "/FREE TEXT", "/FREE TEXT")
rows = Q.verify_rows(r, false)
T.equal(rows[3].head .. rows[3].data, "", "sending: the empty free text lines blank (FMSPG p.324)")
-- four element rows: line 5 left for SEND, the free text on page 2
r = Q.new("REQUEST")
Q.enter(r, "alt", "FL350/FL370", 30000)
Q.select(r, "alt_wx")
Q.enter(r, "hdg", "270", 30000)
rows = Q.verify_rows(r, true)
T.equal(#rows, 9, "four rows, a blank fifth, four free text lines")
T.equal(rows[5].data, "", "line 5 blank")
T.equal(Q.pages(rows), 2, "two pages")
-- ATC INDEX's CLEARANCE and VOICE (FMSPG p.299-300)
local c = Q.new("CLEARANCE")
rows = Q.verify_rows(c, true)
T.equal(rows[1].head .. "=" .. rows[1].data, "REQUEST=CLEARANCE", "REQUEST CLEARANCE")
T.equal(#rows, 4, "three free text lines (FMSPG p.299)")
local v = Q.new("VOICE")
rows = Q.verify_rows(v, true)
T.equal(rows[1].head .. "=" .. rows[1].data, "REQUEST VOICE CONTACT=", "REQUEST VOICE CONTACT in the header")
T.equal(rows[2].head .. rows[2].data, "/FREE TEXT<", "/FREE TEXT (FMSPG p.300)")
local f = Q.new("REQUEST")
rows = Q.verify_rows(f, true)
T.equal(#rows, 4, "nothing selected: lines 1-4 free text (FMSPG p.325)")
T.equal(rows[1].head, "FREE TEXT", "FREE TEXT")
T.check(not Q.sendable(f), "nothing: no SEND")
Q.set_free(f, 2, "REQUEST HIGHER")
T.check(Q.sendable(f), "free text only: SEND")
T.equal(Q.set_free(f, 1, "DELETE"), "INVALID DELETE", "DELETE an empty line")

-- the sent request's pages: four rows under UPLINK and STATUS
r = Q.new("REQUEST")
Q.enter(r, "alt", "FL370", 37000)
Q.select(r, "alt_wx")
Q.set_free(r, 2, "SMOOTH")
rows = Q.sent_rows(r)
T.equal(#rows, 3, "the elements and the free text entered")
T.equal(rows[3].head .. "=" .. rows[3].data, "/FREE TEXT=SMOOTH", "the free text sent")
local many = {}
for k = 1, 10 do many[k] = {head = "", data = "X" .. k} end
T.equal(Q.pages(many, 4), 3, "four on page 1, five after")
local p2, from = Q.page_rows(many, 2, 4)
T.equal(p2[1].data .. "@" .. from, "X5@1", "page 2 from the fifth, line 1")
local p1, from1 = Q.page_rows(many, 1, 4)
T.equal(#p1 .. "@" .. from1, "4@2", "page 1: four from line 2")
Q.erase(r)
T.check(not r.alt and not r.alt_wx and r.free[2] == "", "ERASE REQUEST: everything")
T.done()
