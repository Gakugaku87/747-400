-- Run from the repository root with LuaJIT: luajit tests/fms/atc_report_model_test.lua
-- ATC reports (6-1/6-2 step 12g3c; notes/ATA-34-61-FMC.md §120; FCOM
-- p.748-751; FMSPG p.328-340): the requests found in an uplink's text, the
-- reports' rows (the FMC's values, boxes, CLIMBING TO, DEVIATING), the
-- entries' forms, CANNOT ACCEPT, ARM and its conditions, the text sent.
local T = dofile("tests/lib/check.lua")("atc_report_model")
dofile("plugins/xtlua_keysystems/scripts/B747.68.xt.fms/B747.68.atc_request_model.lua")
local A = dofile("plugins/xtlua_keysystems/scripts/B747.68.xt.fms/B747.68.atc_report_model.lua")

local c = {alt = "FL330", mcp = "FL350", mcp_dir = "CLIMBING", route = "RJAA XAC ATMUG RJBB", rte_name = "RTE 1",
    ensuing = "SPENS", next_wpt = "XAC", next_eta = "1555Z", ppos = "N3530.0E14000.0", last = "BRAVO",
    ata = "1436Z", spd = ".84", hdg = "270", trk = "268", endurance = "05+30", now = "1500Z"}

-- the requests (FMSPG p.328-335)
T.equal(A.parse("CLIMB TO AND MAINTAIN FL350 REPORT REACHING FL350").id, "REPORT REACHING", "REPORT REACHING in a clearance")
T.equal(A.parse("REPORT REACHING FL350").args[1], "FL350", "its altitude")
T.equal(A.parse("REPORT REACHING FL350").armable, "REACHING", "armable (FMSPG p.340)")
T.equal(A.parse("REPORT REACHING BLOCK FL350 TO FL370").id, "REPORT REACHING BLOCK", "REACHING BLOCK first")
T.equal(A.parse("CONFIRM NEXT WAYPOINT ETA").id, "CONFIRM NEXT WAYPOINT ETA", "NEXT WAYPOINT ETA, not NEXT WAYPOINT")
T.equal(A.parse("CONFIRM ASSIGNED ALTITUDE").id, "CONFIRM ASSIGNED ALTITUDE", "ASSIGNED ALTITUDE, not ALTITUDE")
T.equal(#A.parse("CONFIRM ALTITUDE").args, 0, "no arguments")
T.equal(A.parse("WHEN CAN YOU ACCEPT FL370").args[1], "FL370", "WHEN CAN YOU ACCEPT's")
T.check(A.parse("REQUEST POSITION REPORT").posrep, "REQUEST POSITION REPORT: POS REPORT's")
T.equal(A.parse("CLIMB TO AND MAINTAIN FL350"), nil, "no request")

-- CONFIRM ALTITUDE: the altitude now, CLIMBING TO the MCP's (FMSPG p.328)
local r = A.new(A.parse("CONFIRM ALTITUDE"))
local rows = A.rows(r, c)
T.equal(rows[1].head .. "=" .. rows[1].data, "PRESENT ALTITUDE=FL330", "PRESENT ALTITUDE, the FMC's")
T.equal(rows[2].head .. "=" .. rows[2].data, "/CLIMBING TO=FL350", "/CLIMBING TO the MCP's")
T.equal(A.text(r, c), "PRESENT ALTITUDE FL330 CLIMBING TO FL350", "the text")
T.equal(A.enter(r, "alt", "FL335", c), nil, "an entry over it")
T.equal(A.text(r, c), "PRESENT ALTITUDE FL335 CLIMBING TO FL350", "the entry sent")
T.equal(A.enter(r, "alt", "FL335/FL340", c), A.INVALID, "no block here")
T.equal(A.enter(r, "alt", "DELETE", c), nil, "DELETE")
T.equal(A.rows(r, c)[1].data, "FL330", "back to the FMC's")
-- boxes: CONFIRM SQUAWK, ASSIGNED SPEED (FMSPG p.329, p.331)
r = A.new(A.parse("CONFIRM SQUAWK"))
T.equal(A.rows(r, c)[1].data, "****", "SQUAWKING: boxes")
T.check(not A.complete(r, c), "no SEND before the entry")
T.equal(A.enter(r, "code", "1238", c), A.INVALID, "an 8: not a beacon code (FMSPG p.336)")
T.equal(A.enter(r, "code", "1234", c), nil, "a beacon code")
T.check(A.complete(r, c), "complete")
T.equal(A.text(r, c), "SQUAWKING 1234", "SQUAWKING 1234")
-- fixed fields: REPORT LEVEL (FMSPG p.333)
r = A.new(A.parse("REPORT LEVEL FL350"))
T.equal(A.enter(r, "alt", "FL330", c), A.INVALID, "the uplink's altitude: INVALID ENTRY")
T.equal(A.text(r, c), "LEVEL FL350", "LEVEL FL350")
T.equal(A.arm(r, true), nil, "ARM")
T.check(not A.triggered(r, {alt_ft = 33000, vs_fpm = 1500}, 35000), "climbing below: not yet")
T.check(not A.triggered(r, {alt_ft = 34900, vs_fpm = 800}, 35000), "at it but still climbing: not LEVEL")
T.check(A.triggered(r, {alt_ft = 34990, vs_fpm = 50}, 35000), "level at it: sent")
T.equal(A.arm(r, false), nil, "disarmed")
T.check(not A.triggered(r, {alt_ft = 35000, vs_fpm = 0}, 35000), "disarmed: no")
r = A.new(A.parse("REPORT PASSING GGW"))
A.arm(r, true)
T.check(not A.triggered(r, {alt_ft = 0, passed = {XAC = true}}), "not passed yet")
T.check(A.triggered(r, {alt_ft = 0, passed = {GGW = true}}), "passed: sent")
T.equal(A.arm(A.new(A.parse("CONFIRM SPEED")), true), A.INVALID, "not armable")
-- WHEN CAN YOU ACCEPT: AT [time] or CANNOT ACCEPT (FMSPG p.334)
r = A.new(A.parse("WHEN CAN YOU ACCEPT FL370"))
rows = A.rows(r, c)
T.equal(rows[1].head .. "=" .. rows[1].data .. "|" .. rows[2].head .. "=" .. rows[2].data, "WE CAN ACCEPT=FL370|AT=****",
    "WE CAN ACCEPT FL370 AT boxes")
A.enter(r, "time", "1620", c)
T.equal(A.text(r, c), "WE CAN ACCEPT FL370 AT 1620Z", "with the time")
T.equal(A.cannot(r, true), nil, "CANNOT ACCEPT")
T.equal(A.text(r, c), "WE CANNOT ACCEPT FL370", "WE CANNOT ACCEPT")
T.check(A.complete(r, c), "no time needed")
-- DEVIATING with an offset (FMSPG p.329-330)
r = A.new(A.parse("CONFIRM NEXT WAYPOINT"))
T.equal(A.text(r, {next_wpt = "XAC", offset_text = "L10NM"}), "NEXT WAYPOINT XAC DEVIATING L10NM OF ROUTE", "DEVIATING")
T.equal(A.text(r, {next_wpt = "XAC"}), "NEXT WAYPOINT XAC", "no offset: none")
-- the other forms (FMSPG p.336)
T.equal(A.valid("deg", "361"), nil, "degrees 000-360")
T.equal(A.valid("deg", "090"), "090", "three digits")
T.equal(A.valid("dist", "120.5"), "120.5NM", "a distance")
T.equal(A.valid("dist", "1000"), nil, "over 999.9")
T.equal(A.valid("fuel", "05+30"), "05+30", "remaining fuel hh+mm")
T.equal(A.valid("fuel", "25+00"), nil, "hh 00-23")
T.equal(A.valid("souls", "350"), "350", "souls")
T.equal(A.valid("atis", "K"), "K", "ATIS one character")
r = A.new(A.parse("REPORT REMAINING FUEL AND SOULS ON BOARD"))
rows = A.rows(r, c)
T.equal(rows[1].data .. "|" .. rows[2].head .. "=" .. rows[2].data .. "|" .. rows[3].head,
    "05+30|OF FUEL REMAINING AND=***|SOULS ON BOARD", "the FMC's fuel, the souls' boxes")
A.enter(r, "souls", "350", c)
T.equal(A.text(r, c), "05+30 OF FUEL REMAINING AND 350 SOULS ON BOARD", "the text")
-- ASSIGNED ALTITUDE and a block (FMSPG p.329)
r = A.new(A.parse("CONFIRM ASSIGNED ALTITUDE"))
rows = A.rows(r, c)
T.equal(rows[1].data .. "|" .. rows[2].data, "FL350|-----", "the MCP's, dashes for a block")
A.enter(r, "alt2", "FL370", c)
T.equal(A.text(r, c), "ASSIGNED BLOCK FL350 TO FL370", "ASSIGNED BLOCK")
-- free text, RTE REPORT (FMSPG p.338)
local f = A.new()
T.equal(A.text(f, c), "", "FREE TEXT: empty")
A.set_free(f, 1, "WEATHER AHEAD")
T.equal(A.text(f, c), "WEATHER AHEAD", "the free text")
local rt = A.new({id = "RTE REPORT"})
T.equal(A.text(rt, c), "ASSIGNED ROUTE RTE 1 RJAA XAC ATMUG RJBB", "ASSIGNED ROUTE RTE X and the route")
local long = {route = "RJAA RW34L XAC SPENS BOKJO ATMUG RJBB", rte_name = "RTE 1"}
rows = A.rows(rt, long)
T.equal(rows[2].data .. "|" .. rows[3].data, "RJAA RW34L XAC SPENS|BOKJO ATMUG RJBB", "a long route on two lines, by words")
T.done()
